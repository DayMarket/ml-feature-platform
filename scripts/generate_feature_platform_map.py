def _policy_status(record: DagRecord) -> str:
    if not record.expected_severity:
        return "not classified"
    if record.severity == record.expected_severity:
        return "ok"
    return f"expected {record.expected_severity}"


def _format_time(minute_of_day: int) -> str:
    return f"{minute_of_day // 60:02d}:{minute_of_day % 60:02d}"


def _format_delta(minutes: int) -> str:
    if minutes == 0:
        return "0"
    hours, remainder = divmod(minutes, 60)
    if hours and remainder:
        return f"{hours}h {remainder}m"
    if hours:
        return f"{hours}h"
    return f"{remainder}m"


def _internal_dependency_count(records: list[DagRecord]) -> int:
    internal_ids = {record.dag_id for record in records}
    return sum(
        dependency.upstream_dag_id in internal_ids
        for record in records
        for dependency in record.dependencies
    )


def _external_dependency_count(records: list[DagRecord]) -> int:
    internal_ids = {record.dag_id for record in records}
    return sum(
        dependency.upstream_dag_id not in internal_ids
        for record in records
        for dependency in record.dependencies
    )



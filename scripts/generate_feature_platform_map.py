def discover_dags(repo_root: Path) -> list[DagRecord]:
    records: list[DagRecord] = []
    for root_name in DAG_ROOTS:
        root = repo_root / root_name
        if not root.exists():
            continue
        for dag_path in sorted(root.glob("**/dag*.py")):
            records.extend(_parse_dag_file(repo_root, dag_path))

    dag_ids = [record.dag_id for record in records]
    duplicates = sorted({dag_id for dag_id in dag_ids if dag_ids.count(dag_id) > 1})
    if duplicates:
        raise ValueError(f"Duplicate DAG ids in generated map: {duplicates}")

    exclusions = _map_exclusions(repo_root)
    unknown_exclusions = sorted(set(exclusions) - set(dag_ids))
    if unknown_exclusions:
        raise ValueError(
            "Feature Platform map excludes unknown DAG ids: "
            f"{unknown_exclusions}"
        )

    normalized_records = _normalize_trigger_dependencies(
        sorted(records, key=lambda record: record.dag_id)
    )
    visible_records = [
        replace(
            record,
            dependencies=tuple(
                dependency
                for dependency in record.dependencies
                if dependency.upstream_dag_id not in exclusions
            ),
        )
        for record in normalized_records
        if record.dag_id not in exclusions
    ]
    return _apply_severity_policy(visible_records)


def _map_exclusions(repo_root: Path) -> dict[str, str]:
    config_path = repo_root / MAP_CONFIG
    if not config_path.exists():
        return {}
    config = json.loads(config_path.read_text(encoding="utf-8"))
    exclusions = config.get("excluded_dags", {})
    if not isinstance(exclusions, dict):
        raise ValueError(f"{MAP_CONFIG}: excluded_dags must be an object")
    for dag_id, reason in exclusions.items():
        if not isinstance(dag_id, str) or not isinstance(reason, str) or not reason.strip():
            raise ValueError(
                f"{MAP_CONFIG}: every excluded DAG must have a non-empty reason"
            )
    return exclusions


def _critical_group_tags(repo_root: Path, team: str) -> set[str]:
    config_path = repo_root / MAP_CONFIG
    if not config_path.exists():
        return set()
    config = json.loads(config_path.read_text(encoding="utf-8"))
    critical_groups = config.get("critical_groups", {})
    if not isinstance(critical_groups, dict):
        raise ValueError(f"{MAP_CONFIG}: critical_groups must be an object")
    group_tags = critical_groups.get(team, [])
    if not isinstance(group_tags, list) or not all(
        isinstance(group_tag, str) and group_tag.strip() for group_tag in group_tags
    ):
        raise ValueError(
            f"{MAP_CONFIG}: critical_groups.{team} must be a list of non-empty strings"
        )
    return set(group_tags)


def _critical_dag_ids(repo_root: Path, team: str) -> set[str]:
    config_path = repo_root / MAP_CONFIG
    if not config_path.exists():
        return set()
    config = json.loads(config_path.read_text(encoding="utf-8"))
    critical_dags = config.get("critical_dags", {})
    if not isinstance(critical_dags, dict):
        raise ValueError(f"{MAP_CONFIG}: critical_dags must be an object")
    dag_ids = critical_dags.get(team, [])
    if not isinstance(dag_ids, list) or not all(
        isinstance(dag_id, str) and dag_id.strip() for dag_id in dag_ids
    ):
        raise ValueError(
            f"{MAP_CONFIG}: critical_dags.{team} must be a list of non-empty strings"
        )
    return set(dag_ids)


def _parse_dag_file(repo_root: Path, dag_path: Path) -> list[DagRecord]:
    source = dag_path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=dag_path.as_posix())
    config_path = dag_path.parent / "config.yaml"
    config = _read_config(config_path) if config_path.exists() else {}
    config_env = _config_environment(repo_root, dag_path, tree, config)
    referenced_configs = _referenced_configs(repo_root, tree)
    area = _area_for_path(repo_root, dag_path)
    resource = _resource_label(config, dag_path.parent)
    table = _table_name(config)
    records = []

    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        decorator = _dag_decorator(node)
        if decorator is None:
            continue
        keywords = {keyword.arg: keyword.value for keyword in decorator.keywords if keyword.arg}
        dag_id = _eval_string(keywords.get("dag_id"), config_env)
        if not dag_id:
            raise ValueError(f"Cannot resolve dag_id in {dag_path}:{node.lineno}")
        schedule_expression = keywords.get("schedule")
        schedule = _eval_schedule(schedule_expression, config_env)
        if (
            schedule is None
            and schedule_expression is not None
            and not (
                isinstance(schedule_expression, ast.Constant)
                and schedule_expression.value is None
            )
        ):
            raise ValueError(
                f"Cannot resolve schedule in {dag_path}:{node.lineno}"
            )
        dependencies = _dependencies_for_function(
            node,
            config_env,
            config,
            referenced_configs,
            area,
        )
        record_table = table if _owns_output_table(dag_id, config) else None
        records.append(
            DagRecord(
                dag_id=dag_id,
                path=dag_path.relative_to(repo_root).as_posix(),
                area=area,
                schedule=schedule,
                resource=resource,
                table=record_table,
                severity=_configured_severity(config),
                dependencies=tuple(sorted(set(dependencies), key=lambda dep: (dep.upstream_dag_id, dep.kind))),
                group_tag=_configured_group_tag(config),
                is_backfill=_contains_backfill(node),
            )
        )
    return records


def _dag_decorator(node: ast.FunctionDef | ast.AsyncFunctionDef) -> ast.Call | None:
    for decorator in node.decorator_list:
        if isinstance(decorator, ast.Call) and _call_name(decorator.func) == "dag":
            return decorator
    return None


def _dependencies_for_function(
    function: ast.FunctionDef | ast.AsyncFunctionDef,
    config_env: dict[str, Any],
    config: dict[str, Any],
    referenced_configs: list[dict[str, Any]],
    area: str,
) -> list[Dependency]:
    dependencies: list[Dependency] = []
    unresolved_dq_sensor = False
    unresolved_dq_delta = 0
    unresolved_upload_sensor = False
    for call in (node for node in ast.walk(function) if isinstance(node, ast.Call)):
        call_name = _call_name(call.func)
        if call_name == "ExternalTaskSensor":
            expression = _keyword(call, "external_dag_id")
            upstream = _eval_string(expression, config_env)
            delta_minutes = _timedelta_minutes(_keyword(call, "execution_delta"), config_env)
            if upstream:
                dependencies.append(Dependency(upstream, "sensor", delta_minutes))
            elif isinstance(expression, ast.Call) and _call_name(expression.func) == "_dq_dag_id":
                unresolved_dq_sensor = True
                unresolved_dq_delta = delta_minutes
            else:
                unresolved_upload_sensor = True
        elif call_name == "TriggerDagRunOperator":
            upstream = _eval_string(_keyword(call, "trigger_dag_id"), config_env)
            if upstream:
                dependencies.append(Dependency(upstream, "trigger", 0))

    if unresolved_dq_sensor:
        for referenced_config in referenced_configs:
            dq_dag_id = _dq_dag_id(referenced_config)
            if dq_dag_id:
                dependencies.append(Dependency(dq_dag_id, "sensor", unresolved_dq_delta))

    if unresolved_upload_sensor and area == "upload":
        dependencies.extend(_upload_dependencies(config))
    elif unresolved_upload_sensor:
        raise ValueError("Cannot resolve ExternalTaskSensor.external_dag_id")
    return dependencies


def _normalize_trigger_dependencies(records: list[DagRecord]) -> list[DagRecord]:
    """Represent TriggerDagRunOperator as current DAG -> triggered DAG."""
    by_id = {record.dag_id: record for record in records}
    dependencies_by_id = {
        record.dag_id: [dependency for dependency in record.dependencies if dependency.kind != "trigger"]
        for record in records
    }
    for record in records:
        for dependency in record.dependencies:
            if dependency.kind != "trigger":
                continue
            if dependency.upstream_dag_id not in by_id:
                raise ValueError(
                    f"Triggered DAG is not declared in the repository: {dependency.upstream_dag_id}"
                )
            dependencies_by_id[dependency.upstream_dag_id].append(
                Dependency(record.dag_id, "trigger", dependency.delta_minutes)
            )
    return [
        replace(
            record,
            dependencies=tuple(
                sorted(
                    set(dependencies_by_id[record.dag_id]),
                    key=lambda dependency: (dependency.upstream_dag_id, dependency.kind),
                )
            ),
        )
        for record in records
    ]


def _apply_severity_policy(records: list[DagRecord]) -> list[DagRecord]:
    """Classify production, training, and backfill workloads."""
    by_id = {record.dag_id: record for record in records}
    table_producers = {
        record.table: record.dag_id for record in records if record.table
    }
    production_ids = {
        record.dag_id for record in records if record.area == "upload"
    }
    changed = True
    while changed:
        changed = False
        for downstream_id in tuple(production_ids):
            for dependency in by_id[downstream_id].dependencies:
                upstream_id = dependency.upstream_dag_id
                if upstream_id not in by_id:
                    upstream_table = _table_from_dq_dag_id(upstream_id)
                    upstream_id = table_producers.get(upstream_table, "")
                if upstream_id and upstream_id not in production_ids:
                    production_ids.add(upstream_id)
                    changed = True

    classified = []
    for record in records:
        if record.area == "datasets":
            workload = "training"
            expected = "P4"
        elif record.is_backfill:
            workload = "backfill"
            expected = "P4"
        elif record.dag_id in production_ids:
            workload = "production"
            expected = "P3"
        else:
            workload = "other"
            expected = None
        classified.append(
            replace(
                record,
                workload=workload,
                expected_severity=expected,
            )
        )
    return classified


def severity_policy_violations(records: list[DagRecord]) -> list[str]:
    violations = []
    for record in records:
        if record.severity not in {"P3", "P4"}:
            violations.append(
                f"{record.dag_id}: alerts.severity must be P3 or P4, got {record.severity or 'missing'}"
            )
        elif record.expected_severity and record.severity != record.expected_severity:
            violations.append(
                f"{record.dag_id}: {record.workload} workload must be "
                f"{record.expected_severity}, got {record.severity}"
            )
    return violations


def _table_from_dq_dag_id(dag_id: str) -> str | None:
    match = re.fullmatch(
        r"dbt\.source\.trino\.ml_feature_platform_(?P<schema>[^.]+)\."
        r"(?P<table>[^.]+)\.dq",
        dag_id,
    )
    if not match:
        return None
    return f"iceberg.{match.group('schema')}.{match.group('table')}"


def _upload_dependencies(config: dict[str, Any]) -> list[Dependency]:
    dependencies = []
    for feature_group in config.get("feature_groups", []):
        source = feature_group.get("source", {})
        upstream = source.get("dependency_dag_id")
        if upstream:
            dependencies.append(
                Dependency(
                    str(upstream),
                    "upload-sensor",
                    int(source.get("dependency_execution_delta_minutes", 0)),
                )
            )
    return dependencies


def _config_environment(
    repo_root: Path,
    dag_path: Path,
    tree: ast.Module,
    config: dict[str, Any],
) -> dict[str, Any]:
    dag_config = config.get("dag", {})
    env: dict[str, Any] = {
        "CONFIG": config,
        "dag_settings": {
            "dag_id": dag_config.get("id"),
            "schedule": dag_config.get("schedule"),
        },
    }
    path_variables: dict[str, Path] = {"CONFIG_PATH": dag_path.parent / "config.yaml"}
    for assignment in (node for node in tree.body if isinstance(node, ast.Assign)):
        target_names = [target.id for target in assignment.targets if isinstance(target, ast.Name)]
        for target_name in target_names:
            if target_name.endswith("CONFIG_PATH"):
                resolved = _resolve_config_path(repo_root, assignment.value)
                if resolved:
                    path_variables[target_name] = resolved
    for assignment in (node for node in tree.body if isinstance(node, ast.Assign)):
        if not isinstance(assignment.value, ast.Call) or not assignment.value.args:
            continue
        path_arg = assignment.value.args[0]
        if not isinstance(path_arg, ast.Name) or path_arg.id not in path_variables:
            continue
        path = path_variables[path_arg.id]
        if not path.exists():
            continue
        loaded_config = _read_config(path)
        for target in assignment.targets:
            if isinstance(target, ast.Name):
                env[target.id] = loaded_config
    return env


def _referenced_configs(repo_root: Path, tree: ast.Module) -> list[dict[str, Any]]:
    paths: set[Path] = set()
    for call in (node for node in ast.walk(tree) if isinstance(node, ast.Call)):
        resolved = _resolve_config_path(repo_root, call)
        if resolved and resolved.exists() and resolved.name == "config.yaml":
            paths.add(resolved)
    return [_read_config(path) for path in sorted(paths)]


def _resolve_config_path(repo_root: Path, expression: ast.AST) -> Path | None:
    if not isinstance(expression, ast.Call) or _call_name(expression.func) != "join":
        return None
    components = [arg.value for arg in expression.args if isinstance(arg, ast.Constant) and isinstance(arg.value, str)]
    for root_name in DAG_ROOTS:
        if root_name in components:
            start = components.index(root_name)
            return repo_root.joinpath(*components[start:])
    return None


def _read_config(path: Path) -> dict[str, Any]:
    content = path.read_text(encoding="utf-8")
    stripped = content.lstrip()
    if stripped.startswith("{"):
        return json.loads(content)
    return _read_simple_yaml(content)


def _read_simple_yaml(content: str) -> dict[str, Any]:
    result: dict[str, Any] = {}
    stack: list[tuple[int, dict[str, Any]]] = [(-1, result)]
    for raw_line in content.splitlines():
        if not raw_line.strip() or raw_line.lstrip().startswith(("#", "- ")):
            continue
        indent = len(raw_line) - len(raw_line.lstrip(" "))
        line = raw_line.strip()
        if ":" not in line:
            continue
        key, raw_value = line.split(":", 1)
        while stack[-1][0] >= indent:
            stack.pop()
        parent = stack[-1][1]
        raw_value = raw_value.strip()
        if not raw_value:
            nested: dict[str, Any] = {}
            parent[key] = nested
            stack.append((indent, nested))
        else:
            parent[key] = _yaml_scalar(raw_value)
    return result


def _yaml_scalar(value: str) -> Any:
    if value[:1] in {"'", '"'} and value[-1:] == value[:1]:
        try:
            return ast.literal_eval(value)
        except (ValueError, SyntaxError):
            return value[1:-1]
    lowered = value.lower()
    if lowered in {"true", "false"}:
        return lowered == "true"
    if lowered in {"null", "none", "~"}:
        return None
    try:
        return int(value)
    except ValueError:
        return value


def _eval_schedule(expression: ast.AST | None, env: dict[str, Any]) -> str | None:
    if expression is None or (isinstance(expression, ast.Constant) and expression.value is None):
        return None
    if isinstance(expression, ast.Call) and _call_name(expression.func) == "CronDataIntervalTimetable":
        cron_expression = _keyword(expression, "cron") or (expression.args[0] if expression.args else None)
        return _eval_string(cron_expression, env)
    return _eval_string(expression, env)


def _eval_string(expression: ast.AST | None, env: dict[str, Any]) -> str | None:
    value = _eval_value(expression, env)
    return str(value) if value is not None else None


def _eval_value(expression: ast.AST | None, env: dict[str, Any]) -> Any:
    if expression is None:
        return None
    if isinstance(expression, ast.Constant):
        return expression.value
    if isinstance(expression, ast.Name):
        return env.get(expression.id)
    if isinstance(expression, ast.BinOp) and isinstance(expression.op, ast.Add):
        left = _eval_value(expression.left, env)
        right = _eval_value(expression.right, env)
        return left + right if left is not None and right is not None else None
    if isinstance(expression, ast.Subscript):
        container = _eval_value(expression.value, env)
        key = _eval_value(expression.slice, env)
        if isinstance(container, dict) and key in container:
            return container[key]
        return None
    if isinstance(expression, ast.Call) and _call_name(expression.func) in {"int", "str"} and expression.args:
        value = _eval_value(expression.args[0], env)
        if value is None:
            return None
        return int(value) if _call_name(expression.func) == "int" else str(value)
    return None


def _timedelta_minutes(expression: ast.AST | None, env: dict[str, Any]) -> int:
    if not isinstance(expression, ast.Call) or _call_name(expression.func) != "timedelta":
        return 0
    values = {keyword.arg: _eval_value(keyword.value, env) for keyword in expression.keywords if keyword.arg}
    return (
        int(values.get("days", 0) or 0) * 1440
        + int(values.get("hours", 0) or 0) * 60
        + int(values.get("minutes", 0) or 0)
    )


def _keyword(call: ast.Call, name: str) -> ast.AST | None:
    return next((keyword.value for keyword in call.keywords if keyword.arg == name), None)


def _contains_backfill(function: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    return any(
        "backfill" in node.value.lower()
        for node in ast.walk(function)
        if isinstance(node, ast.Constant) and isinstance(node.value, str)
    )


def _call_name(expression: ast.AST) -> str:
    if isinstance(expression, ast.Name):
        return expression.id
    if isinstance(expression, ast.Attribute):
        return expression.attr
    return ""



"""Generate the repository DAG dependency and schedule map."""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Any, Iterable


DAG_ROOTS = ("layers", "datasets", "upload")
DEFAULT_OUTPUT = Path("docs/feature_platform_map.md")
MAP_CONFIG = Path("config/feature_platform_map.json")
DAILY_CRON = re.compile(r"^(?P<minute>\d{1,2})\s+(?P<hour>\d{1,2}|\*/\d{1,2})\s+\*\s+\*\s+\*$")


@dataclass(frozen=True)
class Dependency:
    upstream_dag_id: str
    kind: str
    delta_minutes: int = 0


@dataclass(frozen=True)
class DagRecord:
    dag_id: str
    path: str
    area: str
    schedule: str | None
    resource: str
    table: str | None
    severity: str | None
    dependencies: tuple[Dependency, ...]
    group_tag: str | None = None
    is_backfill: bool = False
    workload: str = "other"
    expected_severity: str | None = None


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path.cwd())
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when the committed map differs from generated content.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    repo_root = args.repo_root.resolve()
    output_path = args.output
    if not output_path.is_absolute():
        output_path = repo_root / output_path

    records = discover_dags(repo_root)
    rendered = render_repository_map(repo_root, records)
    if args.check:
        violations = severity_policy_violations(records)
        if violations:
            print("Feature Platform severity policy violations:", file=sys.stderr)
            for violation in violations:
                print(f"- {violation}", file=sys.stderr)
            return 1
        if not output_path.exists() or output_path.read_text(encoding="utf-8") != rendered:
            print(
                f"{output_path.relative_to(repo_root)} is stale; run "
                "python3 scripts/generate_feature_platform_map.py",
                file=sys.stderr,
            )
            return 1
        print(f"Feature Platform map is current: {output_path.relative_to(repo_root)}")
        return 0

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(rendered, encoding="utf-8")
    print(f"Generated {output_path.relative_to(repo_root)}")
    return 0



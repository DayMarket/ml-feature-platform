def _resource_label(config: dict[str, Any], entity_dir: Path) -> str:
    profiles = sorted(set(_find_values(config, "resource_profile")))
    if profiles:
        return ", ".join(str(profile) for profile in profiles)
    resources = config.get("resources", {})
    if resources or (entity_dir / "config" / "resources.yaml").exists():
        return "spark-custom"
    if config.get("runtime") or config.get("source"):
        return "airflow-python"
    return "unspecified"


def _find_values(value: Any, key: str) -> Iterable[Any]:
    if isinstance(value, dict):
        for child_key, child_value in value.items():
            if child_key == key:
                yield child_value
            yield from _find_values(child_value, key)
    elif isinstance(value, list):
        for child in value:
            yield from _find_values(child, key)


